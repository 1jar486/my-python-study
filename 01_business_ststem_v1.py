while True:
    # 打印主菜单（门面工程）
    print("\n" + "="*40)
    print("      💼 大佬的生意管理后台 v1.0")
    print("="*40)
    print(" 1. 💰 [财务] 实时纯利计算 (单笔/月计)")
    print(" 2. 🎯 [销售] 客户意向智能分级")
    print(" 3. 🛡️ [运维] 数字化资产批量巡检")
    print(" 4. 🏆 [成就] 查看开发者荣誉")
    print(" 0. 🚪 退出系统")
    print("="*40) 
# 逻辑分流
    while True:
        choice = input("请输入操作编号 (0-4): ")
        if choice in ['0', '1', '2', '3',"4"]:
            break # 输入正确跳出循环
        else:
            print("无效输入，请输入 0-4 之间的数字。")
        
    if choice == '1':
        # 导入财务模块
        print("\n>>> 进入[财务模块]\n")
        while True:
            try:
               #功能：计算流水 -> 扣除服务器成本50 -> 净利润
               count = int(input("请输入本月销量: "))
               if count < 0:
                     print("销量不能为负数，请重新输入一个非负整数。")
                     continue #输入错误，继续循环
               break #输入正确后跳出循环
            except ValueError:
                print("输入无效，请输入一个纯数字。例如: 20)，不要输入文字、字母或者特殊字符")
        profit = 199 * 0.95 * count - 50
        print(f"本月净利润: {profit:.2f} 元")
    elif choice == '2':
        # 导入销售模块
        print("\n>>> 进入[销售模块]\n")
        while True:
            try:
                consult = int(input("请输入该客户累积咨询次数: "))
                if consult < 0:
                    print("咨询次数不能为负数，请重新输入一个非负整数。")
                    continue
                break #输入正确后跳出循环   
            except ValueError:
                print("输入无效，请输入一个纯数字。(例如: 20)，不要输入文字、字母或者特殊字符")
        if consult >= 50:
            print("行动建议：疑似同行，建议拉黑。") 
        elif 10 <= consult < 50:
            print("级别：核心VIP")
            print("行动建议：亲自接待，提供一对一服务。")   
        elif 5 <= consult < 10:
            print("级别：高意向客户")
            print("行动建议：发送优惠券，引导转化。")
        elif 0 <= consult < 5:
            print("级别：普通路人")
            print("行动建议：只发自动回复，节省精力。")
    elif choice == '3':
        # 导入运维模块
        print("\n>>> 进入[运维模块]\n")
        my_projects = ["闲鱼自动引流脚本", "海外问卷调查自动化",
             "外卖红包监控插件","虚拟资源发货机",
             "汇率变动预警器","自动交易机器人",
             "大户监控系统"]
        print(">>> 正在启动[个人数字资产]每日巡检系统...\n")
        for project in my_projects: #模拟检查动作
            print(f"正在巡检项目: {project}......[状态：运行中]")
        total_count = len(my_projects)
        print("-"*30) #分割线
        print(f"巡检完成！当前共有 {total_count} 个项目正常运行。")
        print("老板辛苦了，祝你今日收益翻倍！")
    elif choice == '4':
        # 统一格式：图标 + 两个字标题 + 全角冒号
        print("🥇 开发者：21岁创业大佬")
        # 注意：在“状”和“态”中间加一个【全角空格】（在中文输入法下按空格）
        # 或者直接复制下面这两行，我已经帮你调好了最稳的间距
        print("🚀 状　态：已掌握基础逻辑、异常处理、循环嵌套") 
        print("🗓️  目　标：年薪 20 万倒计时 1095 天")
    elif choice == '0':
        print("正在安全退出系统... 再见！")
        break